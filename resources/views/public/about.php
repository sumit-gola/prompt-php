        <p class="eyebrow">About / Editorial standard</p>
        <h1>Useful image prompts, selected with context.</h1>
        <p class="trust-lede">MyPromptArt is an independently operated, editorially managed library of completed AI image prompts. It is maintained by the MyPromptArt editorial team for creators who want to understand, adapt, and reuse a prompt without sorting through unfinished drafts.</p>
    </div>

    <div class="trust-grid" aria-label="How MyPromptArt operates">
        <section class="trust-card">
            <p class="trust-label">Library</p>
            <h2>What MyPromptArt provides</h2>
            <p>Visitors can browse categories, search the collection, open a complete prompt, review its available context, and copy the prompt text. Public visitors do not upload images or generate new prompts on the website.</p>
        </section>

        <section class="trust-card">
            <p class="trust-label">Selection</p>
            <h2>How prompts are selected</h2>
            <p>Entries are reviewed for completeness, practical detail, visual direction, and usefulness. Empty, failed, pending, and duplicate-looking records stay outside the public library until they are suitable for publication.</p>
        </section>

        <section class="trust-card">
            <p class="trust-label">Testing</p>
            <h2>What “tested with” means</h2>
            <p>Editorial selection is not the same as model testing. A prompt page names a tested model only when that test has been recorded by the editorial team. If no verified test is recorded, the page says so plainly.</p>
        </section>

        <section class="trust-card">
            <p class="trust-label">Compatibility</p>
            <h2>Supported image models</h2>
            <p>Most prompts are model-flexible and can be adapted for systems such as Gemini, ChatGPT Image, Midjourney, and other text-to-image tools. Results vary by model, version, reference image, aspect ratio, and safety settings.</p>
        </section>

        <section class="trust-card">
            <p class="trust-label">Sources &amp; rights</p>
            <h2>How source material is handled</h2>
            <p>Source names and links are retained when they are available. Attribution does not transfer ownership: prompts, trademarks, and preview images remain subject to their respective owners&rsquo; rights. Licensing, attribution, or removal concerns are reviewed through the published contact address.</p>
        </section>

        <section class="trust-card">
            <p class="trust-label">Cadence</p>
            <h2>How often the library changes</h2>
            <p>The library is updated as new entries complete editorial review rather than on a fixed publishing quota. Prompt pages show their publication date and a separate last-reviewed date when a review has been recorded.</p>
        </section>
