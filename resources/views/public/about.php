    <p class="eyebrow">About</p>
    <h1>MyPromptArt publishes completed AI image prompts.</h1>
    <p>MyPromptArt is an editorially managed library for discovering practical AI image prompts. Public visitors can browse categories, search the collection, open a prompt, and copy its finished text.</p>
    <p>Every public entry has completed the site&rsquo;s publication workflow. Draft, pending, processing, failed, and empty prompts remain outside the public library and search index.</p>
    <p>Prompt pages may include a visual preview, category, negative prompt, style notes, publication dates, and related completed prompts. Private creation and generation tools remain restricted to administrators.</p>
